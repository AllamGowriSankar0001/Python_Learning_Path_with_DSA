# Store name, age, salary and print them using variables
name = "John" # This is a string variable,
age = 20 # This is an integer variable,
salary = 20000.00 # This is a float variable,
print(name, age, salary) # This will print the values of the variables to the console,

# Store name, age, salary and print them using multiple assignment
name,age,salary = "John",20,20000.00 # This is a multiple assignment,
print(name,age,salary)
# we can have multiple variables in one line like this: name,age,salary = "John",20,20000.00
