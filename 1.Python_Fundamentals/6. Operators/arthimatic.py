#Arithmetic Operators
a = 10
b = 5
print(a+b) #addition of a and b
print(a-b) #subtraction of a and b
print(a*b) #multiplication of a and b
print(a/b) #division(quotient) of a and b
print(a//b) #floor division(quotient) of a and b
print(a%b) #modulus(remainder) of a and b
print(a**b) #exponentiation of a and b
