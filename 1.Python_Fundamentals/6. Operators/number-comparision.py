#Number Comparision
a = 10
b = 5
print(a>b) #true if a is greater than b
print(a<b) #true if a is less than b
print(a>=b) #true if a is greater than or equal to b
print(a<=b) #true if a is less than or equal to b
print(a==b) #true if a is equal to b
print(a!=b) #true if a is not equal to b
print(a is b) #true if a and b are the same object
print(a is not b) #true if a and b are not the same object
print(a is None) #true if a is None
print(a is not None) #true if a is not None
print(a is True) #true if a is True
print(a is not True) #true if a is not True
print(a is False) #true if a is False
print(a is not False) #true if a is not False