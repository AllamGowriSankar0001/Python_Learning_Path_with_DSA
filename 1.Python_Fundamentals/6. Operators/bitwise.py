#Bitwise Operators
a = 5 #binary: 0101
b = 3 #binary: 0011
print(a&b) #bitwise and (0101 & 0011 = 0001)
print(a|b) #bitwise or (0101 | 0011 = 0111)
print(a^b) #bitwise xor (0101 ^ 0011 = 0110)
print(~a) #bitwise not (0101 = 1010)
print(a<<1) #bitwise left shift (0101 << 1 = 1010)
print(a>>1) #bitwise right shift (0101 >> 1 = 0010)