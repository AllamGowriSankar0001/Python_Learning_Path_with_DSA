#Membership Operators
a = "Hello World"
print("Hello" in a) #true if "Hello" is in a (case sensitive)
print("Hello" not in a) #true if "Hello" is not in a (case sensitive)
print("World" in a) #true if "World" is in a (case sensitive)
print("World" not in a) #true if "World" is not in a (case sensitive)
print("hello" in a) #true if "hello" is in a (case sensitive)
print("hello" not in a) #true if "hello" is not in a (case sensitive)
print("world" in a) #true if "world" is in a (case sensitive)
print("world" not in a) #true if "world" is not in a (case sensitive)
