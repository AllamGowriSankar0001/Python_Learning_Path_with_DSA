# Get inputs
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))
sum = num1 + num2
print(f"Sum: {sum}") #this will print the sum of num1 and num2
difference = num1 - num2
print(f"Difference: {difference}") #this will print the difference of num1 and num2
product = num1 * num2
print(f"Product: {product}") #this will print the product of num1 and num2
quotient = num1 / num2
print(f"Quotient: {quotient}") #this will print the quotient of num1 and num2